// Copies the capture-guide SVGs from the photographer app (Bricks-Dispatch web/src/guide/data/svg)
// into src/lib/help/diagrams/svgs.ts, themed with CSS variables so they work in light and dark mode.
// Usage: node scripts/build-help-diagrams.mjs <path-to-svg-dir>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir) throw new Error('Pass the guide svg directory')
const COLOURS = {
  '#14110E': 'var(--ink)',
  '#615D57': 'var(--inkSoft)',
  '#97928A': 'var(--inkMute)',
  '#B7B2AA': 'var(--inkFaint)',
  '#F4F1EB': 'var(--paper)',
}
const out = {}
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  let s = readFileSync(join(dir, f), 'utf8')
  const inner = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
  let body = inner
    .replace(/<title[^>]*>[\s\S]*?<\/title>/, '')
    .replace(/<rect id="bg"[^>]*\/>/, '')
    // Bottom caption: the article renders its own caption below the figure.
    .replace(/<text x="24" y="276"[^>]*>[\s\S]*?<\/text>/g, '')
    .replace(/font-family="'General Sans'[^"]*"/g, 'font-family="var(--font-sans, inherit)"')
    .replace(/font-family="'JetBrains Mono'[^"]*"/g, 'font-family="var(--font-mono, ui-monospace, monospace)"')
    .replace(/font-size="11"/g, 'font-size="14"')
    .replace(/font-size="12"/g, 'font-size="14"')
    .replace(/font-size="13"/g, 'font-size="15"')
    .replace(/\s+/g, ' ')
    .trim()
  for (const [hex, v] of Object.entries(COLOURS)) body = body.split(`"${hex}"`).join(`"${v}"`)
  if (/#[0-9A-Fa-f]{6}/.test(body)) throw new Error(`Unmapped colour in ${f}`)
  out[f.replace(/\.svg$/, '')] = body
}
const ts = `// Generated by scripts/build-help-diagrams.mjs from the photographer app's capture guide. Do not edit.
import type { DiagramId } from '../types'

export const DIAGRAM_VIEWBOX = '0 0 480 264'

export const DIAGRAMS: Record<DiagramId, string> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(new URL('../src/lib/help/diagrams/svgs.ts', import.meta.url), ts)
console.log(Object.keys(out).length, 'diagrams')
